// Builds the stand-in catalogue for the Collection pages from
// scripts/stock/catalogue-demo.json:
//   products -> public/demo/p-<slug>-<width>.webp (4:5)
//   heroes   -> public/demo/sc-<name>-<width>.webp (16:9)
//   seeds/demo-catalogue.sql (products, images, hero photos)
// Originals are cached in .stock/originals/ (not committed). Entries are
// merged into public/demo/sizes.json.
//
// Usage: node scripts/stock/make-catalogue.mjs

import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "../..");
const spec = JSON.parse(readFileSync(path.join(root, "scripts/stock/catalogue-demo.json"), "utf8"));
const outDir = path.join(root, "public/demo");
const cacheDir = path.join(root, ".stock/originals");
mkdirSync(cacheDir, { recursive: true });

const UA = { "User-Agent": "WhyCreativesSiteBuilder/1.0 (hello@whycreatives.in)" };
const PRODUCT = { aspect: [4, 5], widths: [480, 800, 1200] };
const HERO = { aspect: [16, 9], widths: [640, 1080, 1600, 2048] };

const slugify = (s) =>
  s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^\w\s-]/g, "")
    .trim()
    .replace(/[\s_]+/g, "-")
    .replace(/-+/g, "-");
const sql = (v) => (v == null ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

async function original(key) {
  const src = spec.sources[key];
  if (!src) throw new Error(`unknown source ${key}`);
  const file = path.join(cacheDir, `cat-src-${key}.jpg`);
  if (existsSync(file)) return file;
  const url = src.pexels
    ? `https://images.pexels.com/photos/${src.pexels}/pexels-photo-${src.pexels}.jpeg?auto=compress&cs=tinysrgb&w=3000`
    : src.url;
  // Retries: the image hosts sometimes drop a connection mid-download.
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url, { headers: UA });
      if (!res.ok) throw new Error(`${res.status} for ${url}`);
      writeFileSync(file, Buffer.from(await res.arrayBuffer()));
      return file;
    } catch (e) {
      if (attempt >= 4) throw e;
      await new Promise((r) => setTimeout(r, 2000 * attempt));
    }
  }
}

// Cuts the box (fractions of the photo: x, y, width, height), then the
// largest centred piece of the target shape, recolours, and saves widths.
async function make(name, item, { aspect, widths }) {
  const file = await original(item.src);
  const upright = await sharp(file).rotate().toBuffer();
  const meta = await sharp(upright).metadata();
  const [bx, by, bw, bh] = item.crop ?? [0, 0, 1, 1];
  let left = Math.round(bx * meta.width);
  let top = Math.round(by * meta.height);
  let w = Math.min(meta.width - left, Math.round(bw * meta.width));
  let h = Math.min(meta.height - top, Math.round(bh * meta.height));
  const [aw, ah] = aspect;
  if (w / h > aw / ah) {
    const nw = Math.round((h * aw) / ah);
    left += Math.round((w - nw) / 2);
    w = nw;
  } else {
    const nh = Math.round((w * ah) / aw);
    top += Math.round((h - nh) / 2);
    h = nh;
  }
  let img = sharp(upright).extract({ left, top, width: w, height: h });
  if (item.modulate) img = img.modulate(item.modulate);
  if (item.tint) img = img.tint(item.tint);
  const piece = await img.toBuffer();
  const made = [];
  for (const width of widths) {
    if (width > w * 1.15) continue;
    await sharp(piece)
      .resize(width, Math.round((width * ah) / aw))
      .webp({ quality: width >= 1200 ? 68 : 72, effort: 6 })
      .toFile(path.join(outDir, `${name}-${width}.webp`));
    made.push(width);
  }
  if (made.length === 0) {
    // Small source: one size at its own width.
    const width = Math.floor(w / 16) * 16;
    await sharp(piece).resize(width).webp({ quality: 72 }).toFile(path.join(outDir, `${name}-${width}.webp`));
    made.push(width);
  }
  return { widths: made, aspect, px: w };
}

// Start clean: remove the files from an earlier run.
for (const f of readdirSync(outDir)) if (/^(p|sc)-.*\.webp$/.test(f)) unlinkSync(path.join(outDir, f));

const sizesFile = path.join(outDir, "sizes.json");
const sizes = JSON.parse(readFileSync(sizesFile, "utf8"));
for (const k of Object.keys(sizes)) if (/^(p|sc)-/.test(k)) delete sizes[k];

for (const hero of spec.heroes) {
  const r = await make(hero.name, hero, HERO);
  sizes[hero.name] = { widths: r.widths, aspect: r.aspect };
  console.log(`hero    ${hero.name.padEnd(34)} ${r.widths.join(", ")}`);
}

const lines = [
  "-- GENERATED by scripts/stock/make-catalogue.mjs from scripts/stock/catalogue-demo.json.",
  "-- LOCAL DESIGN PREVIEW ONLY (and the live preview build). Stand-in products",
  "-- for the Collection pages; the client's own products replace them.",
  "DELETE FROM product_images;",
  "DELETE FROM products;",
];
// Descriptions are real site copy, kept in migrations/0008_catalogue_descriptions.sql.
for (const [slug, key] of Object.entries(spec.categoryHeroes)) lines.push(`UPDATE categories SET hero_image_key = ${sql(key)} WHERE slug = ${sql(slug)};`);
lines.push(`INSERT INTO settings (key, value) VALUES ('collection_hero_image', 'demo/sc-collection') ON CONFLICT (key) DO UPDATE SET value = excluded.value;`);

const SUB_CATEGORY = { 1: [10, 11, 12, 13, 14, 15, 16, 17, 20], 2: [100, 110, 111, 112, 113, 114, 115, 120, 121, 122, 130, 131, 132, 133, 134, 140, 150, 200, 201, 202, 203, 204, 205], 3: [300, 301] };
const categoryOf = (sub) => Number(Object.entries(SUB_CATEGORY).find(([, ids]) => ids.includes(sub))?.[0]);

const seen = new Set();
const position = {};
for (const [i, p] of spec.products.entries()) {
  const id = 1000 + i;
  const cat = p.cat ?? categoryOf(p.in);
  if (!cat) throw new Error(`no category for ${p.name}`);
  let slug = slugify(p.name);
  while (seen.has(`${cat}/${slug}`)) slug += "-2";
  seen.add(`${cat}/${slug}`);
  const key = `p-${cat}-${slug}`;
  const r = await make(key, p, PRODUCT);
  sizes[key] = { widths: r.widths, aspect: r.aspect };
  const group = p.in ?? `c${cat}`;
  position[group] = (position[group] ?? 0) + 1;
  const largest = Math.max(...r.widths);
  lines.push(
    `INSERT INTO products (id, category_id, subcategory_id, slug, name, position) VALUES (${id}, ${cat}, ${p.in ?? "NULL"}, ${sql(slug)}, ${sql(p.name)}, ${position[group]});`,
    `INSERT INTO product_images (product_id, image_key, width, height, alt, position) VALUES (${id}, ${sql(`demo/${key}`)}, ${largest}, ${Math.round((largest * 5) / 4)}, ${sql(p.name)}, 1);`,
  );
  console.log(`product ${key.padEnd(42)} ${r.widths.join(", ")}${r.px < 900 ? `  (source only ${r.px}px wide)` : ""}`);
}

writeFileSync(sizesFile, JSON.stringify(sizes, null, 2) + "\n");
writeFileSync(path.join(root, "seeds/demo-catalogue.sql"), lines.join("\n") + "\n");
console.log(`done: ${spec.products.length} products, seeds/demo-catalogue.sql written`);
